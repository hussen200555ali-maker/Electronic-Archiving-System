        public void LoadData()
        {
            try
            {
                if (userRole == "مدير")
                {
                    entityInstantFeedbackSource2.Refresh();

                    // كود إعادة تحميل البيانات من قاعدة البيانات
                    // وتحديث الـ GridControl أو أي عنصر عرض تستخدمه
                    db = new DBEArchieEntity();
                    gridControl1.DataSource = db.TBUsers.ToList();
                    gridControl1.RefreshDataSource();
                }
                else if (userRole == "مدير قسم")
                {
                    entityInstantFeedbackSource2.Refresh();

                    // كود إعادة تحميل البيانات من قاعدة البيانات
                    // وتحديث الـ GridControl أو أي عنصر عرض تستخدمه
                    db = new DBEArchieEntity();
                    gridControl1.DataSource = db.TBUsers.Where(x => x.DeptName == userDept).ToList();
                    gridControl1.RefreshDataSource();
                }

            }
            catch (Exception ex)
            {
                XtraMessageBox.Show($"خطأ في تحميل البيانات: {ex.Message}", "خطأ",
                    MessageBoxButtons.OK, MessageBoxIcon.Error);
            }
        }
        private void entityInstantFeedbackSource1_GetQueryable(object sender, GetQueryableEventArgs e)
        {
            if (userRole == "مدير")
            {
                // إنشاء سياق البيانات
                var context = new DBEArchieEntity();

                // تعيين مصدر البيانات
                e.QueryableSource = context.TBUsers; // استبدل TBUsers باسم جدولك

                // تخزين السياق للتخلص منه لاحقاً
                e.Tag = context;
            }
            else if(userRole =="مدير قسم")
            {// إنشاء سياق البيانات
                var context = new DBEArchieEntity();

                // تعيين مصدر البيانات
                e.QueryableSource = context.TBUsers.Where(x=> x.DeptName ==userDept); // استبدل TBUsers باسم جدولك

                // تخزين السياق للتخلص منه لاحقاً
                e.Tag = context;

            }
        }

        private void entityInstantFeedbackSource1_DismissQueryable(object sender, GetQueryableEventArgs e)
        {
            // التخلص من سياق البيانات
            var context = e.Tag as DBEArchieEntity;
            context?.Dispose();
        }


