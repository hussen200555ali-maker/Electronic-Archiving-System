        // This event is generated by Data Source Configuration Wizard
        void entityInstantFeedbackSource2_GetQueryable(object sender, GetQueryableEventArgs e)
        {
            // Instantiate a new DataContext
            Electronic_Archive.Pages.DBEArchieEntity dataContext = new Electronic_Archive.Pages.DBEArchieEntity();
            // Assign a queryable source to the EntityInstantFeedbackSource
            e.QueryableSource = dataContext.TBUsers;
            // Assign the DataContext to the Tag property,
            // to dispose of it in the DismissQueryable event handler
            e.Tag = dataContext;
        }

        // This event is generated by Data Source Configuration Wizard
        void entityInstantFeedbackSource2_DismissQueryable(object sender, GetQueryableEventArgs e)
        {
            // Dispose of the DataContext
            ((Electronic_Archive.Pages.DBEArchieEntity)e.Tag).Dispose();
        }

