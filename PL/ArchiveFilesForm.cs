        private bool Delete(ArchiveFile Data)
        {

            try
            {
                db = new DBEArchieEntity();
                db.Entry(Data).State = System.Data.Entity.EntityState.Deleted;
                db.SaveChanges();
                state = true;
            }
            catch
            {
                state = false;
            }
            return state;


        }

