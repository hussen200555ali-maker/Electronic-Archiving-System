        void entityInstantFeedbackSource1_GetQueryable(object sender, DevExpress.Data.Linq.GetQueryableEventArgs e)
        {
            DBEArchieEntity dataContext = new DBEArchieEntity();
            
            e.QueryableSource = dataContext.TBArchive1.Where(X => X.IDCategory == AchiveID)
                .Select(x => new
                {
                    x.ID,
                    x.IDCategory,
                    x.AddDate,
                    x.ArchDate,
                    x.ArchDep,
                    x.ArchDetails,
                    x.ArchNumber,
                    x.ArchReciver,
                    x.ArchSender,
                    x.ArchiveTitle
                });
            e.Tag = dataContext;
        }

        public void LoadData()
        {          // This line of code is generated by Data Source Configuration Wizard
