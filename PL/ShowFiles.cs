        /// <summary>
        /// حفظ الملف مع بناء الهيكل التنظيمي (الوظيفة الوحيدة المطلوبة)
        /// </summary>
        private bool SaveFileWithStructure()
        {
            try
            {
                id = Convert.ToInt32(gridView1.GetFocusedRowCellValue("ID"));

                using (var context = new DBEArchieEntity())
                {
                    var file = context.ArchiveFiles
                        .Where(x => x.ID == id)
                        .Select(x => new { x.FileName, x.FileExtension, x.FileData })
                        .FirstOrDefault();

                    if (file?.FileData != null)
                    {
                        path = BuildFilePath(file.FileName, file.FileExtension);
                        Directory.CreateDirectory(Path.GetDirectoryName(path));

                        var decryptedData = DecryptData(file.FileData);
                        File.WriteAllBytes(path, decryptedData);

                        return true;
                    }
                    return false;
                }
            }
            catch (Exception ex)
            {
                MessageBox.Show($"خطأ الحفظ: {ex.Message}");
                return false;
            }
        }

